static void draw_char(int x, int y, char c, uint32_t color, int scale) {
    if (c < 32 || c > 127) c = '?';
    const uint8_t* glyph = FONT[c - 32];
    for (int row = 0; row < 7; row++) {
        for (int col = 0; col < 5; col++) {
            if (glyph[row] & (1 << (4 - col))) {
                for (int sy = 0; sy < scale; sy++)
                    for (int sx = 0; sx < scale; sx++)
                        draw_pixel(x + col*scale + sx,
                                   y + row*scale + sy, color);
            }
        }
    }
}

int text_width(const char* text, int scale) {
    int len = 0;
    while (*text++) len++;
    return len * (5 * scale + scale);
}

void draw_text(int x, int y, const char* text, uint32_t color, int scale) {
    int cx = x;
    int cw = 5 * scale + scale;
    for (; *text; text++) {
        if (*text == '\n') { cx = x; y += 7 * scale + scale; continue; }
        draw_char(cx, y, *text, color, scale);
        cx += cw;
    }
}

void draw_text_centered(int y, const char* text, uint32_t color, int scale) {
    int w = text_width(text, scale);
    draw_text((SCREEN_WIDTH - w) / 2, y, text, color, scale);
}

void draw_text_right(int x, int y, const char* text, uint32_t color, int scale) {
    int w = text_width(text, scale);
    draw_text(x - w, y, text, color, scale);
}

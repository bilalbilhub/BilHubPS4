#include "renderer.h"
#include <orbis/libkernel.h>
#include <orbis/VideoOut.h>
#include <string.h>
#include <stdlib.h>

uint32_t* g_framebuffer = nullptr;

static int  g_video_handle = -1;
static int  g_buf_index    = 0;
static void* g_buffers[2]  = { nullptr, nullptr };
static const int BUFFER_COUNT = 2;

bool renderer_init() {
    g_video_handle = sceVideoOutOpen(SCE_USER_SERVICE_USER_ID_SYSTEM,
                                     SCE_VIDEO_OUT_BUS_TYPE_MAIN, 0, nullptr);
    if (g_video_handle < 0) return false;

    SceVideoOutResolutionStatus res;
    sceVideoOutGetResolutionStatus(g_video_handle, &res);

    SceVideoOutBufferAttribute attr;
    sceVideoOutSetBufferAttribute(&attr,
        SCE_VIDEO_OUT_PIXEL_FORMAT_B8_G8_R8_A8_SRGB,
        SCE_VIDEO_OUT_TILING_MODE_LINEAR,
        SCE_VIDEO_OUT_ASPECT_RATIO_16_9,
        SCREEN_WIDTH, SCREEN_HEIGHT,
        SCREEN_WIDTH * sizeof(uint32_t));

    size_t buf_size = SCREEN_WIDTH * SCREEN_HEIGHT * sizeof(uint32_t);

    for (int i = 0; i < BUFFER_COUNT; i++) {
        g_buffers[i] = sceKernelMapNamedSystemFlexibleMemory(
            nullptr, buf_size, 0x62, SCE_KERNEL_MAP_NAMED_ANONYMOUS, -1, 0,
            "BilHubFB");
        if (!g_buffers[i]) return false;
        memset(g_buffers[i], 0, buf_size);
    }

    int reg = sceVideoOutRegisterBuffers(g_video_handle, 0, g_buffers, BUFFER_COUNT, &attr);
    if (reg < 0) return false;

    g_framebuffer = (uint32_t*)g_buffers[0];
    return true;
}

void renderer_shutdown() {
    if (g_video_handle >= 0) {
        sceVideoOutClose(g_video_handle);
        g_video_handle = -1;
    }
}

void renderer_clear(uint32_t color) {
    uint32_t* fb = (uint32_t*)g_buffers[g_buf_index];
    int total = SCREEN_WIDTH * SCREEN_HEIGHT;
    for (int i = 0; i < total; i++) fb[i] = color;
}

void renderer_flip() {
    sceVideoOutSubmitFlip(g_video_handle, g_buf_index, SCE_VIDEO_OUT_FLIP_MODE_VSYNC, 0);
    g_buf_index   = (g_buf_index + 1) % BUFFER_COUNT;
    g_framebuffer = (uint32_t*)g_buffers[g_buf_index];
}

// ======================= رسم =======================

void draw_rect(int x, int y, int w, int h, uint32_t color) {
    for (int row = y; row < y + h; row++)
        for (int col = x; col < x + w; col++)
            draw_pixel(col, row, color);
}

void draw_rect_outline(int x, int y, int w, int h,
                       uint32_t fill, uint32_t border, int t) {
    draw_rect(x, y, w, h, fill);
    draw_rect(x, y, w, t, border);           // top
    draw_rect(x, y+h-t, w, t, border);      // bottom
    draw_rect(x, y, t, h, border);          // left
    draw_rect(x+w-t, y, t, h, border);      // right
}

void draw_rounded_rect(int x, int y, int w, int h, uint32_t color, int r) {
    // داخل (بدون زوايا)
    draw_rect(x+r, y,   w-2*r, h,   color);
    draw_rect(x,   y+r, r,     h-2*r, color);
    draw_rect(x+w-r, y+r, r,   h-2*r, color);
    // زوايا دائرية (تقريب بالمربعات)
    for (int dy = 0; dy < r; dy++) {
        for (int dx = 0; dx < r; dx++) {
            if (dx*dx + dy*dy <= r*r) {
                draw_pixel(x+r-1-dx,   y+r-1-dy,   color);
                draw_pixel(x+w-r+dx,   y+r-1-dy,   color);
                draw_pixel(x+r-1-dx,   y+h-r+dy,   color);
                draw_pixel(x+w-r+dx,   y+h-r+dy,   color);
            }
        }
    }
}

void draw_line(int x1, int y1, int x2, int y2, uint32_t color, int thickness) {
    int dx = abs(x2-x1), dy = abs(y2-y1);
    int sx = x1<x2?1:-1, sy = y1<y2?1:-1;
    int err = dx-dy;
    while (true) {
        for (int t = 0; t < thickness; t++) draw_pixel(x1, y1+t, color);
        if (x1==x2 && y1==y2) break;
        int e2 = 2*err;
        if (e2 > -dy) { err -= dy; x1 += sx; }
        if (e2 <  dx) { err += dx; y1 += sy; }
    }
}

void draw_progress_bar(int x, int y, int w, int h,
                       float pct, uint32_t bg, uint32_t fill) {
    draw_rounded_rect(x, y, w, h, bg, 6);
    int fw = (int)(w * pct);
    if (fw > 4) draw_rounded_rect(x, y, fw, h, fill, 6);
}

